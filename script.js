storyButtons.forEach(button => {
    button.addEventListener('click', function() {
        const storyId = this.getAttribute('data-story');
        displayStory(storyId);
    });
});

// Add click event listeners to story items (entire container including image)
storyItems.forEach(item => {
    item.addEventListener('click', function() {
        const storyId = this.getAttribute('data-story');
        displayStory(storyId);
    });
});

// Close button click event
closeButton.addEventListener('click', closeStory);

// Close modal when clicking outside the content
storyDisplay.addEventListener('click', function(e) {
    if (e.target === storyDisplay) {
        closeStory();
    }
});

// Close modal with Escape key
document.addEventListener('keydown', function(e) {
    if (e.key === 'Escape' && !storyDisplay.classList.contains('hidden')) {
        closeStory();
    }
});
